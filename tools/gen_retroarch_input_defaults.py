#!/usr/bin/env python3
"""Generate src/openemux/core/retroarch_input_defaults.py (issue #759).

Every launch starts its input configuration from RetroArch's own defaults, so
a key the user changed in their ``retroarch.cfg`` cannot mix into OpenEmux's
bindings. Those defaults are read out of the real binary rather than typed:

1. Write a config that holds nothing but null drivers, so nothing opens a
   window or touches a device, and lets RetroArch save on exit::

       video_driver = "null"
       audio_driver = "null"
       input_driver = "null"
       joypad_driver = "null"
       menu_driver = "null"
       config_save_on_exit = "true"

2. Run the vendored RetroArch against it with an empty home, and stop it::

       env -i PATH=/usr/bin:/bin HOME=$TMP/home XDG_CONFIG_HOME=$TMP/home/.config \\
           XDG_RUNTIME_DIR=$TMP/run timeout -s TERM 8 \\
           vendors/RetroArch-Linux-x86_64/usr/bin/retroarch --config $TMP/ra.cfg --menu

   On SIGTERM it saves every setting it knows into ``ra.cfg``.

3. ``python3 tools/gen_retroarch_input_defaults.py $TMP/ra.cfg 1.22.2``

Regenerate whenever the vendored RetroArch is bumped.
"""

import re
import sys
from pathlib import Path

OUTPUT = (
    Path(__file__).resolve().parents[1]
    / "src" / "openemux" / "core" / "retroarch_input_defaults.py"
)

PLAYERS = 16

#: Not bindings: platform plumbing whose "default" is either the null driver
#: step 1 asked for or depends on the machine, and on-screen overlay settings,
#: which overlay_bar owns. The overlay and OSK *hotkeys* stay in.
EXCLUDED = {
    "input_driver",
    "input_joypad_driver",
    "input_keyboard_layout",
    "input_remapping_directory",
}
EXCLUDED_PREFIXES = ("input_overlay", "input_osk_overlay")
KEPT_DESPITE_PREFIX = re.compile(r"^input_overlay_next(_btn|_axis|_mbtn)?$")

#: Computed per player instead of stored: their default is the port number - 1.
INDEX_SUFFIXES = ("joypad_index", "mouse_index")

LINE = re.compile(r'^(input_[a-z0-9_]+) = "(.*)"$')
PLAYER = re.compile(r"^input_player(\d+)_(.+)$")


def _excluded(key):
    if key in EXCLUDED:
        return True
    if key.startswith(EXCLUDED_PREFIXES):
        return not KEPT_DESPITE_PREFIX.match(key)
    return False


def read(path):
    values = {}
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        match = LINE.match(line.strip())
        if match and not _excluded(match.group(1)):
            values[match.group(1)] = match.group(2)
    return values


def split(values):
    global_defaults = {}
    players = {}
    for key, value in values.items():
        match = PLAYER.match(key)
        if match:
            players.setdefault(int(match.group(1)), {})[match.group(2)] = value
        else:
            global_defaults[key] = value
    if sorted(players) != list(range(1, PLAYERS + 1)):
        raise SystemExit(f"expected players 1-{PLAYERS}, found {sorted(players)}")
    template = dict(players[2])
    for number in range(2, PLAYERS + 1):
        found = dict(players[number])
        for suffix in INDEX_SUFFIXES:
            if found.pop(suffix) != str(number - 1):
                raise SystemExit(f"player {number}: {suffix} is not {number - 1}")
        if number == 2:
            template = found
        elif found != template:
            raise SystemExit(f"player {number} differs from player 2")
    first = dict(players[1])
    for suffix in INDEX_SUFFIXES:
        if first.pop(suffix) != "0":
            raise SystemExit(f"player 1: {suffix} is not 0")
    if set(first) != set(template):
        raise SystemExit("player 1 has different keys from player 2")
    player1 = {suffix: value for suffix, value in first.items() if template[suffix] != value}
    return global_defaults, template, player1


def _dict(name, values, comment):
    lines = [f"#: {comment}", f"{name} = {{"]
    lines += [f"    {key!r}: {value!r}," for key, value in sorted(values.items())]
    lines.append("}")
    return "\n".join(lines)


def render(version, global_defaults, template, player1):
    return "\n\n".join([
        f'"""RetroArch {version}\'s default value for every input key (issue #759).\n\n'
        "Generated by tools/gen_retroarch_input_defaults.py from the config the\n"
        "vendored RetroArch saves on exit -- do not edit by hand; regenerate when\n"
        "the vendored RetroArch is bumped. Values are unquoted.\n"
        '"""',
        f"RETROARCH_VERSION = {version!r}\n\n"
        f"PLAYERS = {PLAYERS}\n\n"
        "#: Per-player keys computed rather than stored: port N defaults to N - 1.\n"
        f"INDEX_SUFFIXES = {INDEX_SUFFIXES!r}",
        _dict("GLOBAL_DEFAULTS", global_defaults, "Keys that belong to no player."),
        _dict("PLAYER_DEFAULTS", template,
              "input_player<N>_<suffix> for players 2-16, the index keys aside."),
        _dict("PLAYER1_DEFAULTS", player1,
              "Where player 1 differs: the stock keyboard and light-gun binds."),
    ]) + "\n"


def main(argv):
    if len(argv) != 3:
        raise SystemExit(f"usage: {argv[0]} <saved retroarch.cfg> <retroarch version>")
    global_defaults, template, player1 = split(read(argv[1]))
    OUTPUT.write_text(render(argv[2], global_defaults, template, player1), encoding="utf-8")
    print(
        f"{OUTPUT}: {len(global_defaults)} global keys, {len(template)} per player, "
        f"{len(player1)} player-1 differences"
    )


if __name__ == "__main__":
    main(sys.argv)
